#!/usr/bin/env python3
"""Regenerate If97Tables.kt from the IAPWS-IF97 coefficient tables.

The numbers are taken from the Python reference implementation of IAPWS-IF97
(`pip install iapws`), which stores the official R7-97 tables in
`iapws.iapws97.Const`. This is a developer tool: the generated Kotlin file is
committed, so building the app never needs Python.

Usage:
    python3 tools/gen_if97_tables.py
"""
import os

import iapws.iapws97 as m97

C = m97.Const
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(
    ROOT, "app", "src", "main", "java", "com", "steam", "if97", "core", "If97Tables.kt"
)


def doubles(name, values):
    body = ", ".join(repr(float(v)) for v in values)
    return "    val %s = doubleArrayOf(%s)\n" % (name, body)


def ints(name, values):
    body = ", ".join(str(int(v)) for v in values)
    return "    val %s = intArrayOf(%s)\n" % (name, body)


def main():
    out = []
    out.append("package com.steam.if97.core\n\n")
    out.append("/**\n")
    out.append(" * IAPWS-IF97 coefficient tables (R7-97 tables 2, 11, 18 and 30).\n")
    out.append(" * Generated by tools/gen_if97_tables.py - do not edit by hand.\n")
    out.append(" */\n")
    out.append("internal object If97Tables {\n\n")

    out.append("    // Region 1: 34 coefficients (table 2)\n")
    out.append(doubles("R1_N", C.Region1_n))
    out.append(ints("R1_I", C.Region1_Li))
    out.append(ints("R1_J", C.Region1_Lj))

    out.append("\n    // Region 2 residual part: 43 coefficients (table 11)\n")
    out.append(doubles("R2_N", C.Region2_n))
    out.append(ints("R2_I", C.Region2_Li))
    out.append(ints("R2_J", C.Region2_Lj))

    out.append("\n    // Region 2 ideal-gas part: 9 coefficients (table 11, cp0)\n")
    out.append(doubles("R2_N0", C.Region2_cp0_no))
    out.append(ints("R2_J0", C.Region2_cp0_Jo))

    out.append("\n    // Region 3: 39 coefficients (table 30); the n1*ln(delta) term\n")
    out.append("    // is implemented directly in Region3.kt\n")
    out.append(doubles("R3_N", C.Region3_n))
    out.append(ints("R3_I", C.Region3_Li))
    out.append(ints("R3_J", C.Region3_Lj))

    out.append("}\n")

    with open(TARGET, "w", encoding="utf-8") as fh:
        fh.write("".join(out))
    print("wrote %s" % TARGET)


if __name__ == "__main__":
    main()
